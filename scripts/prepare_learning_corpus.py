"""Stream a pinned natural corpus, screen duplicates, freeze reusable packing.

Raw text, token arrays and provenance stay outside Git. This uses no generator
or teacher. Whole documents are retained; no short-document/tail window filter.
"""

import argparse
import concurrent.futures as cf
import hashlib
import itertools
import json
import multiprocessing as mp
import os
import shutil
import sqlite3
import time
from collections import Counter, deque
from pathlib import Path

import numpy as np

from compute_trainium.corpus_audit import NearDuplicateIndex, text_sketch
from compute_trainium.data import content_hash, source_group, split_for_group
from compute_trainium.training import file_sha256
from scripts.prepare_natural import SOURCES, TOKENIZER_REV, download, rows


def reserve(root):
    if min(shutil.disk_usage(p).free for p in (root, Path("/"))) < 35*1024**3:
        raise RuntimeError("Data preparation disk reserve failed")
    memory = dict(line.split(":", 1) for line in Path("/proc/meminfo").read_text().splitlines())
    if int(memory["MemAvailable"].split()[0])*1024 < 512*1024**3:
        raise RuntimeError("Data preparation memory reserve failed")


def worker_init(tokenizer_path):
    global TOKENIZER
    os.environ["TOKENIZERS_PARALLELISM"] = "false"
    from tokenizers import Tokenizer
    TOKENIZER = Tokenizer.from_file(tokenizer_path)


def process_batch(batch):
    output = []
    for domain, shard, row in batch:
        text = row.get("text", row.get("content", ""))
        source = row.get("repo_name", "") if domain == "code" else row.get("url", "")
        license_name = str(row.get("license", "")).lower()
        reason = None
        if domain == "code" and (row.get("autogenerated", False) or license_name not in
                {"mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "isc", "unlicense", "cc0-1.0"}):
            reason = "license_or_generated_code_filter"
        try:
            group = source_group(domain, source)
        except ValueError:
            reason = "missing_source"
        if not reason and (not text or len(text) > 100_000):
            reason = "text_length_filter"
        if reason:
            output.append({"reject": reason})
            continue
        ids = TOKENIZER.encode(text, add_special_tokens=False).ids
        if not 64 <= len(ids) <= 8192:
            output.append({"reject": "token_length_filter"})
            continue
        key = content_hash(text)
        split = split_for_group(group)
        cohort = ("tune" if int(hashlib.sha256(("curve-v1:"+group).encode()).hexdigest()[:16], 16)%2 == 0
                  else "curve") if split == "dev" else None
        signature, sketch = text_sketch(text)
        output.append({"domain": domain, "id": key, "group": hashlib.sha256(group.encode()).hexdigest(),
                       "split": split, "cohort": cohort, "tokens": ids, "source": source,
                       "license": license_name, "shard": shard,
                       "signature": signature, "sketch": sketch})
    return output


def interleaved_batches(domain, paths):
    readers = [(i, iter(rows(p))) for i, p in enumerate(paths)]
    while readers:
        active = []
        for shard, reader in readers:
            batch = [(domain, shard, row) for row in itertools.islice(reader, 256)]
            if batch:
                yield batch
                active.append((shard, reader))
        readers = active


def bounded_map(executor, function, iterable, pending=32):
    iterator, queue = iter(iterable), deque()
    for item in itertools.islice(iterator, pending):
        queue.append(executor.submit(function, item))
    while queue:
        yield queue.popleft().result()
        item = next(iterator, None)
        if item is not None:
            queue.append(executor.submit(function, item))


def freeze_packing(root, database, train_tokens, context, seed=23):
    """Shuffle document records within domains, then deficit-schedule by tokens."""
    import random
    records, arrays = {}, {}
    for domain in ("web", "math", "code"):
        records[domain] = database.execute("select id,offset,length from documents where domain=? and split='train' order by id",
                                           (domain,)).fetchall()
        random.Random(f"{seed}:{domain}").shuffle(records[domain])
        arrays[domain] = np.memmap(root/(domain+".u16"), mode="r", dtype=np.uint16)
    total_length = sum(train_tokens.values()) + 2*sum(map(len, records.values()))
    windows = (total_length-1+context-1)//context
    path = root/"packed"
    path.mkdir()
    tokens = np.lib.format.open_memmap(path/"tokens.npy", mode="w+", dtype=np.int32,
                                      shape=(windows*context+1,))
    domains = np.lib.format.open_memmap(path/"domains.npy", mode="w+", dtype=np.uint8,
                                       shape=tokens.shape)
    tokens[:] = 2
    domains[:] = 0
    served, cursor = dict.fromkeys(records, 0), dict.fromkeys(records, 0)
    weights = {"web": .6, "math": .2, "code": .2}
    offset, order = 0, hashlib.sha256()
    first = True
    while any(cursor[d] < len(records[d]) for d in records):
        domain = min((d for d in records if cursor[d] < len(records[d])), key=lambda d: (served[d]/weights[d], d))
        key, begin, length = records[domain][cursor[domain]]
        cursor[domain] += 1
        tokens[offset] = 1
        tokens[offset+1:offset+1+length] = arrays[domain][begin:begin+length]
        tokens[offset+1+length] = 2
        domains[offset+1:offset+1+length] = 1+list(records).index(domain)
        offset += length+2
        served[domain] += length
        order.update(("" if first else "\n").encode()+key.encode())
        first = False
    tokens.flush()
    domains.flush()
    counts = np.lib.format.open_memmap(path/"prefix_counts.npy", mode="w+", dtype=np.int64,
                                      shape=(windows+1, 3))
    counts[0] = 0
    for start in range(0, windows, 16384):
        end = min(windows, start+16384)
        label = domains[1+start*context:1+end*context].reshape(end-start, context)
        block = np.stack([(label == d).sum(1) for d in (1, 2, 3)], 1)
        counts[start+1:end+1] = block.cumsum(0) + counts[start]
    counts.flush()
    fingerprint = hashlib.sha256()
    for array in (tokens, domains):
        for start in range(0, len(array), 1024*1024):
            fingerprint.update(array[start:start+1024*1024].tobytes())
    source = {"schema": "natural-learning-v1", "synthetic_generation": False,
              "train_domain_targets": served, "data_seed": seed, "context": context,
              "tokenizer_revision": TOKENIZER_REV, "order_fingerprint": order.hexdigest()}
    (root/"source.json").write_text(json.dumps(source, indent=2)+"\n")
    manifest = {"context": context, "seed": seed, "windows": windows,
                "real_targets": sum(served.values()), "domain_counts": served,
                "fingerprint": fingerprint.hexdigest(), "order_fingerprint": order.hexdigest(),
                "source_sha256": file_sha256(root/"source.json"),
                "files": {p.name: file_sha256(p) for p in path.glob("*.npy")}}
    (path/"manifest.json").write_text(json.dumps(manifest, indent=2)+"\n")
    return manifest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--train-tokens", type=int, default=1_050_000_000)
    parser.add_argument("--workers", type=int, default=24)
    parser.add_argument("--shards", type=int, default=6, help="Math/code source files")
    parser.add_argument("--web-shards", type=int, default=2)
    args = parser.parse_args()
    root = args.output.resolve()
    root.mkdir(parents=True, exist_ok=False)
    old = Path("/run/user/1000/autonomous-compute/data-v1")
    reserve(root)
    started = time.monotonic()
    tokenizer = old/"tokenizer.json"
    sources = {}
    def fetch(item):
        domain, index = item
        repo, rev, name = SOURCES[domain]
        if domain in ("web", "math"):
            name = name.replace("train-00000-", f"train-{index:05d}-")
        else:
            name = name.replace("000000000001", f"{index+1:012d}")
        path = old/(domain+(".json.gz" if domain == "code" else ".parquet")) if index == 0 else root/(domain+f"-{index}"+(".json.gz" if domain == "code" else ".parquet"))
        digest = download(f"https://huggingface.co/datasets/{repo}/resolve/{rev}/{name}", path)
        return domain, index, path, {"repository": repo, "revision": rev, "file": name, "sha256": digest}
    with cf.ThreadPoolExecutor(3) as pool:
        for domain, index, path, receipt in pool.map(fetch, [(d, i) for d in SOURCES for i in range(args.web_shards if d == "web" else args.shards)]):
            sources.setdefault(domain, []).append((index, path, receipt))
    db = sqlite3.connect(root/"documents.sqlite")
    db.execute("create table documents(id text primary key,domain text,source_group text,split text,cohort text,offset integer,length integer,source text,license text,shard integer)")
    seen, near = set(), NearDuplicateIndex()
    rejected, counts, eval_docs, train_counts = Counter(), {}, [], {}
    os.environ["OMP_NUM_THREADS"] = "1"
    os.environ["MKL_NUM_THREADS"] = "1"
    with cf.ProcessPoolExecutor(args.workers, mp_context=mp.get_context("spawn"),
                                initializer=worker_init, initargs=(str(tokenizer),)) as pool:
        for domain, weight in (("web", .6), ("math", .2), ("code", .2)):
            quotas = {"train": int(args.train_tokens*weight), "tune": 64_000, "curve": 256_000, "test": 128_000}
            accepted = Counter()
            offset = 0
            with (root/(domain+".u16")).open("wb") as stream:
                for batch in bounded_map(pool, process_batch, interleaved_batches(domain, [p for _, p, _ in sources[domain]]), args.workers*2):
                    reserve(root)
                    for doc in batch:
                        if "reject" in doc:
                            rejected[domain+"/"+doc["reject"]] += 1
                            continue
                        bucket = doc["cohort"] if doc["split"] == "dev" else doc["split"]
                        if accepted[bucket] >= quotas[bucket]:
                            continue
                        if doc["id"] in seen:
                            rejected[domain+"/exact_duplicate"] += 1
                            continue
                        reason = near.check(doc["signature"], doc["sketch"])
                        if reason:
                            rejected[domain+"/"+reason] += 1
                            continue
                        seen.add(doc["id"])
                        near.add(doc.pop("signature"), doc.pop("sketch"))
                        length = len(doc["tokens"])
                        db.execute("insert into documents values(?,?,?,?,?,?,?,?,?,?)",
                                   (doc["id"], domain, doc["group"], doc["split"], doc["cohort"], offset,
                                    length, doc["source"], doc["license"], doc["shard"]))
                        if bucket == "train":
                            np.array(doc["tokens"], dtype=np.uint16).tofile(stream)
                            offset += length
                        else:
                            eval_docs.append(doc)
                        accepted[bucket] += length
                    db.commit()
                    if sum(accepted.values())//10_000_000 != counts.get(domain+"/progress", -1):
                        counts[domain+"/progress"] = sum(accepted.values())//10_000_000
                        print(json.dumps({"domain": domain, "accepted_targets": dict(accepted),
                                          "seconds": time.monotonic()-started}), flush=True)
                    if all(accepted[k] >= quotas[k] for k in quotas):
                        break
            if not all(accepted[k] >= quotas[k] for k in quotas):
                raise RuntimeError(f"Insufficient unique natural {domain} data: {dict(accepted)} vs {quotas}; add immutable shards")
            train_counts[domain] = accepted["train"]
            counts[domain] = dict(accepted)
    # Source-group split and tuning/curve group disjointness are audited explicitly.
    overlap = db.execute("select count(*) from (select source_group from documents group by source_group having count(distinct split)>1 or count(distinct cohort)>1)").fetchone()[0]
    if overlap:
        raise AssertionError("Source groups cross splits or tuning/curve cohorts")
    (root/"dev.json").write_text(json.dumps([d for d in eval_docs if d["split"] == "dev"]))
    (root/"test-sealed.json").write_text(json.dumps([d for d in eval_docs if d["split"] == "test"]))
    packing = freeze_packing(root, db, train_counts, 1024)
    groups = db.execute("select domain,split,cohort,count(*),count(distinct source_group),sum(length) from documents group by domain,split,cohort").fetchall()
    report = {"status": "PASS_FROZEN_NATURAL_CORPUS", "synthetic_generation": False,
              "sources": {d: [r for _, _, r in v] for d, v in sources.items()},
              "tokenizer": {"revision": TOKENIZER_REV, "sha256": file_sha256(tokenizer), "vocab_size": 32000},
              "counts": counts, "group_counts": groups, "rejected": dict(rejected),
              "source_group_overlap": overlap,
              "near_duplicate_audit": {"method": "32 affine uint64 minhash, 8 bands x 4, bottom-256 five-word shingle Jaccard estimate >=0.8",
                                        "crowded_buckets_rejected": True, "exact_global_dedup": True,
                                        "limit": "Approximate lexical screening; not exhaustive semantic deduplication"},
              "packing": packing, "dev_sha256": file_sha256(root/"dev.json"),
              "test_sha256": file_sha256(root/"test-sealed.json"),
              "preparation_wall_seconds": time.monotonic()-started}
    (root/"manifest.json").write_text(json.dumps(report, indent=2)+"\n")
    print(json.dumps(report, indent=2), flush=True)


if __name__ == "__main__":
    main()
